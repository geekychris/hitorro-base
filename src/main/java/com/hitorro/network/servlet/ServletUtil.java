package com.hitorro.network.servlet;

import com.hitorro.util.commandandcontrol.Command;
import com.hitorro.util.commandandcontrol.CommandRegistry;
import com.hitorro.util.commandandcontrol.RestOperations;
import com.hitorro.util.core.string.StringUtil;
import jakarta.servlet.http.HttpServletResponse;

import java.io.IOException;
import java.io.PrintWriter;
import java.util.HashMap;
import java.util.Map;
import java.util.Set;

/**
 * A collection of methods to make writing simple servlets easier.
 *
 * @author chris
 */
public final class ServletUtil {

	// form types
	public static final int PostFormType = 3;
	public static final int GetFormType = 4;

	/**
	 * Start a standard HTML response and put in a simple header. This creates a usual text html response with UTF-8
	 * character set and a title.  The html generated by this routine ends with the body open tag.
	 *
	 * @param response the response we're starting
	 * @param title    the title to put on the page
	 * @throws IOException if there is trouble writing
	 */
	public static void startHtmlResponse(HttpServletResponse response, String title)
			throws IOException {
		response.setContentType("text/html");
		response.setStatus(HttpServletResponse.SC_OK);
		PrintWriter out = response.getWriter();
		out.println("<html>");
		out.println("<head>");
		out.println("<meta http-equiv=\"content-type\" content=\"text/html; charset=UTF-8\">");
		out.print("<title>");
		writeEscapedText(out, title);
		out.println("</title>");
		out.println("</head>");
		out.println("<body>");
	}

	/**
	 * Finish a standard HTML response. This method will close body and html tags.
	 *
	 * @throws IOException if there is trouble writing
	 */
	public static void finishHtmlResponse(HttpServletResponse response)
			throws IOException {
		PrintWriter out = response.getWriter();
		out.println("</body>");
		out.println("</html>");
	}

	/**
	 * Write a line of text heading.
	 */
	public static void writeHeading(HttpServletResponse response, String text, int headLevel)
			throws IOException {
		PrintWriter out = response.getWriter();
		String headTag = StringUtil.strcat("h", headLevel);

		out.print("<");
		out.print(headTag);
		out.print(">");

		writeEscapedText(out, text);

		out.print("</");
		out.print(headTag);
		out.println(">");
	}

	public static void startTable(HttpServletResponse response)
			throws IOException {
		PrintWriter out = response.getWriter();
		out.println("<table>");
	}

	public static void writeTableHeaders(HttpServletResponse response, String[] headers, int nColumns)
			throws IOException {
		writeRowHelper(response, headers, nColumns, null, "th");
	}

	public static void writeTableRow(HttpServletResponse response, String[] values, ValueWriter[] vwriters, int nColumns)
			throws IOException {
		writeRowHelper(response, values, nColumns, vwriters, "td");
	}

	public static void writeLink(HttpServletResponse response, String href, String label)
			throws IOException {
		PrintWriter out = response.getWriter();
		out.print("<a href=\"");
		out.print(href);
		out.print("\">");
		writeEscapedText(out, label);
		out.print("</a>");
	}

	private static void writeRowHelper(HttpServletResponse response, String[] values,
									   int nColumns, ValueWriter[] vwriters, String tag)
			throws IOException {
		PrintWriter out = response.getWriter();
		out.println("<tr>");
		for (int ii = 0; ii < nColumns; ii++) {
			out.print("<");
			out.print(tag);
			out.print(">");
			String value = "";
			if (values != null && ii < values.length) {
				value = values[ii];
			}
			if (vwriters != null && vwriters[ii] != null) {
				vwriters[ii].write(response, value);
			} else {
				writeEscapedText(out, values[ii]);
			}
			out.print("</");
			out.print(tag);
			out.print(">");
		}
		out.println("</tr>");
	}

	public static void endTable(HttpServletResponse response)
			throws IOException {
		PrintWriter out = response.getWriter();
		out.println("</table>");
	}

	public static void startForm(HttpServletResponse response, String url, int formtype)
			throws IOException {
		PrintWriter out = response.getWriter();
		out.print("<form action=\"");
		out.print(url);
		if (formtype == GetFormType) {
			out.print("\" method=\"GET\">");
		} else {
			out.print("\" method=\"POST\">");
		}
		out.println();
	}

	public static void writeFormInput(HttpServletResponse response, String label, String name, String value)
			throws IOException {
		PrintWriter out = response.getWriter();
		writeEscapedText(out, label);
		out.print(": ");
		out.print("<input type=text name=\"");
		out.print(name);
		out.print("\" value=\"");
		String val = (value != null) ? value : "";
		writeEscapedText(out, val);
		out.println("\" maxlength=300>");
	}

	public static void writeFormHidden(HttpServletResponse response, String name, String value)
			throws IOException {
		PrintWriter out = response.getWriter();
		out.print("<input type=hidden name=\"");
		out.print(name);
		out.print("\" value=\"");
		String val = (value != null) ? value : "";
		writeEscapedText(out, val);
		out.println("\" maxlength=30>");
	}

	public static void endForm(HttpServletResponse response, String submitLabel)
			throws IOException {
		PrintWriter out = response.getWriter();
		out.print("<input type=submit value=\"");
		out.print(submitLabel);
		out.println("\">");
		out.println("</form>");
	}

	public static void writeHorizontalLine(HttpServletResponse response)
			throws IOException {
		PrintWriter out = response.getWriter();
		out.println("<hr/>");
	}

	public static void writeBreak(HttpServletResponse response)
			throws IOException {
		PrintWriter out = response.getWriter();
		out.println("<br/>");
	}

	public static void writeText(HttpServletResponse response, String text)
			throws IOException {
		writeEscapedText(response.getWriter(), text);
	}

	public static void writeBoldText(HttpServletResponse response, String text)
			throws IOException {
		PrintWriter out = response.getWriter();
		out.print("<b>");
		writeEscapedText(out, text);
		out.print("</b>");
	}

	/**
	 * Write out text, escaped for HTML.
	 *
	 * @param out  output goes here
	 * @param text the raw text, needing escape
	 */
	private static void writeEscapedText(PrintWriter out, String text) {
		out.print(StringUtil.encodeForXML(text));
	}

	public static Map<String, String> getArgs(Map<String, String[]> params) {
		Map<String, String> p = new HashMap<String, String>();
		Set<Map.Entry<String, String[]>> set = params.entrySet();
		for (Map.Entry<String, String[]> entry : set) {
			String v = getZerothElement(entry.getValue());
			if (v != null) {
				p.put(entry.getKey(), v);
			}
		}
		return p;
	}

	public static final String getZerothElement(String[] s) {
		if (s == null || s.length == 0) {
			return null;
		}
		return s[0];
	}

	public static Command computeArgs(String verb, Map<String, String[]> params,
									  HttpServletResponse response,
									  RestOperations op)
			throws IOException {
		if (params == null) {
			// can't find it
			response.sendError(404);
			return null;
		}

		if (StringUtil.nullOrEmptyOrBlankString(verb)) {
			// can't find it
			if (response != null) {
				response.sendError(404);
			}
			return null;
		}
		verb = verb.substring(1);
		Command dc = CommandRegistry.getRegistry().get(verb);
		if (dc == null) {
			// can't find it
			if (response != null) {
				response.sendError(404);
			}
			return null;
		}
		if (dc.getSupportsOperation(op)) {
			return dc;
		}
		return null;
	}

	/**
	 * Class for doing special formatting of values, used for formatting table cell values.
	 *
	 * @author chris
	 */
	public static class ValueWriter {
		public void write(HttpServletResponse response, String value)
				throws IOException {
			// default implementation just writes out the text
			writeText(response, value);
		}
	}

}
